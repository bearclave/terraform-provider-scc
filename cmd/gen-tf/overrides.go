package main

// Per-noun overrides for resources whose cmdlets do not fit the generic
// New/Get/Set/Remove mapping. The generator adjusts the attributes here and
// emits zz_generated_overrides.go, which lists for each overridden noun the
// behaviour that hand-written code in internal/provider/overrides*.go
// implements on top of the generated resource:
//
//   - DeltaLists: a list that only New-* takes and that Set-* changes through
//     -Add<X> / -Remove<X> (label policy labels, every policy *_location). The
//     attribute is updated in place instead of forcing replacement; the
//     override computes the added and removed values from state and plan.
//   - SetOnly: a parameter only Set-* takes (Set-Label -Priority). The
//     override applies it with Set-* right after New-*, so a configured value
//     does not need a second apply.
//
// The generator fails when an override names a parameter the catalog does not
// have, so a catalog change cannot silently drop one.

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/terraprovider/go-exoscc/spec"
	"github.com/terraprovider/tf-msadmin/genframework"
)

type nounOverride struct {
	// Drop lists parameters that are not exposed as attributes: the
	// -Add<X>/-Remove<X> companions of DeltaLists are added to it
	// automatically. Action switches that select their own Set-* parameter set
	// (-RetryDistribution) or rename the object (-NewName) belong here too.
	Drop []string
}

// overrides is keyed by noun. Every noun listed needs a hand-written override
// in internal/provider (TestOverridesCoverGeneratedMetadata checks this).
var overrides = map[string]nounOverride{
	"Label":                     {},
	"LabelPolicy":               {Drop: []string{"RetryDistribution"}},
	"DlpCompliancePolicy":       {Drop: []string{"RetryDistribution", "NewName"}},
	"DlpComplianceRule":         {},
	"RetentionCompliancePolicy": {Drop: []string{"RetryDistribution"}},
	"RetentionComplianceRule":   {},
}

type overrideMeta struct {
	Noun       string
	DeltaLists []string
	SetOnly    []string
}

// applyOverrides adjusts the overridden resources in place and returns the
// metadata zz_generated_overrides.go carries.
func applyOverrides(resources []genframework.Resource, byNoun map[string]map[string]spec.Cmdlet, partial bool) ([]overrideMeta, error) {
	var metas []overrideMeta
	seen := map[string]bool{}
	for i := range resources {
		r := &resources[i]
		o, ok := overrides[r.Noun]
		if !ok || r.Config || r.DataSourceOnly {
			continue
		}
		seen[r.Noun] = true
		verbs := byNoun[r.Noun]
		inNew, inSet := paramSet(verbs["New"]), paramSet(verbs["Set"])

		drop := map[string]bool{}
		for _, d := range o.Drop {
			if !inNew[d] && !inSet[d] {
				return nil, fmt.Errorf("override %s: no parameter %s on New-/Set-%s", r.Noun, d, r.Noun)
			}
			drop[exportName(d)] = true
		}
		meta := overrideMeta{Noun: r.Noun}
		for _, a := range r.Attributes {
			name := a.APIName
			if a.Type != genframework.TypeStringSet || !inNew[name] || inSet[name] {
				continue
			}
			if !inSet["Add"+name] || !inSet["Remove"+name] {
				continue
			}
			meta.DeltaLists = append(meta.DeltaLists, name)
			drop["Add"+name] = true
			drop["Remove"+name] = true
		}
		deltas := map[string]bool{}
		for _, d := range meta.DeltaLists {
			deltas[d] = true
		}

		kept := r.Attributes[:0]
		for _, a := range r.Attributes {
			if drop[a.Field] {
				continue
			}
			if deltas[a.Field] {
				// Updated in place by the override through -Add/-Remove.
				a.Replace = false
				a.InUpdate = false
			}
			if a.InUpdate && !a.InCreate {
				meta.SetOnly = append(meta.SetOnly, a.Field)
			}
			kept = append(kept, a)
		}
		r.Attributes = kept
		sort.Strings(meta.DeltaLists)
		sort.Strings(meta.SetOnly)
		metas = append(metas, meta)
	}
	for noun := range overrides {
		if !seen[noun] && !partial {
			return nil, fmt.Errorf("override %s: noun not generated", noun)
		}
	}
	sort.Slice(metas, func(i, j int) bool { return metas[i].Noun < metas[j].Noun })
	return metas, nil
}

// renderOverrides emits zz_generated_overrides.go.
func renderOverrides(metas []overrideMeta) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen-tf; DO NOT EDIT.\n\npackage provider\n\n")
	b.WriteString("// generatedOverrides lists, per overridden noun, the attributes the\n")
	b.WriteString("// hand-written override applies (see cmd/gen-tf/overrides.go).\n")
	b.WriteString("var generatedOverrides = map[string]overrideMeta{\n")
	for _, m := range metas {
		fmt.Fprintf(&b, "\t%q: {\n", m.Noun)
		fmt.Fprintf(&b, "\t\tDeltaLists: %s,\n", goStrings(m.DeltaLists))
		fmt.Fprintf(&b, "\t\tSetOnly: %s,\n", goStrings(m.SetOnly))
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func goStrings(v []string) string {
	if len(v) == 0 {
		return "nil"
	}
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
